// Command germanyborder regenerates Germany's border for the zone layer
// (§ 5 KCanG applies only in Germany). It reads an Osmosis .poly of OSM
// relation 51477, simplifies each ring with Douglas-Peucker and writes the
// same rings, as encoded polylines, for the backend and for the app:
//
//	curl -o germany.poly 'https://polygons.openstreetmap.fr/get_poly.py?id=51477&params=0'
//	go run ./cmd/germanyborder -poly germany.poly
//
// Run it from backend/. Data © OpenStreetMap contributors (ODbL).
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"math"
	"os"
	"strconv"
	"strings"

	"stonerspots/backend/internal/zones"
)

type pt = [2]float64 // lat, lon

func main() {
	poly := flag.String("poly", "", "Osmosis .poly file of OSM relation 51477 (required)")
	tol := flag.Float64("tol", 20, "simplification tolerance in metres")
	goOut := flag.String("go", "internal/zones/germany_border.txt", "backend output")
	dartOut := flag.String("dart", "../app/lib/features/zones/germany_border.g.dart", "app output")
	flag.Parse()
	if *poly == "" {
		flag.Usage()
		os.Exit(2)
	}
	rings, err := readPoly(*poly)
	if err != nil {
		log.Fatal(err)
	}
	var lines []string
	total := 0
	for _, r := range rings {
		s := simplifyRing(r, *tol)
		total += len(s)
		lines = append(lines, zones.EncodePolyline(s))
	}
	head := fmt.Sprintf("Germany's border: OSM relation 51477, outer rings only, simplified to %g m.\n"+
		"Data © OpenStreetMap contributors (ODbL). Generated by backend/cmd/germanyborder; do not edit.", *tol)

	var g strings.Builder
	for _, l := range strings.Split(head, "\n") {
		g.WriteString("# " + l + "\n")
	}
	for _, l := range lines {
		g.WriteString(l + "\n")
	}
	if err := os.WriteFile(*goOut, []byte(g.String()), 0o644); err != nil {
		log.Fatal(err)
	}

	var d strings.Builder
	for _, l := range strings.Split(head, "\n") {
		d.WriteString("// " + l + "\n")
	}
	d.WriteString("// The backend embeds the same rings (backend/internal/zones/germany_border.txt).\n\n")
	d.WriteString("/// Encoded polylines (precision 1e-5), one per ring.\n")
	d.WriteString("const List<String> kGermanyBorderRings = [\n")
	for _, l := range lines {
		d.WriteString("  r'" + l + "',\n")
	}
	d.WriteString("];\n")
	if err := os.WriteFile(*dartOut, []byte(d.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%d rings, %d points\n", len(rings), total)
}

// readPoly reads the outer rings of an Osmosis .poly file (holes are refused).
func readPoly(path string) ([][]pt, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Scan() // file name
	var rings [][]pt
	var cur []pt
	in := false
	for sc.Scan() {
		s := strings.TrimSpace(sc.Text())
		switch {
		case s == "":
		case !in && s == "END":
			return rings, sc.Err()
		case !in:
			if strings.HasPrefix(s, "!") {
				return nil, fmt.Errorf("hole %q: not supported", s)
			}
			in, cur = true, nil
		case s == "END":
			in = false
			rings = append(rings, cur)
		default:
			f := strings.Fields(s)
			if len(f) != 2 {
				return nil, fmt.Errorf("bad line %q", s)
			}
			lon, err1 := strconv.ParseFloat(f[0], 64)
			lat, err2 := strconv.ParseFloat(f[1], 64)
			if err1 != nil || err2 != nil {
				return nil, fmt.Errorf("bad line %q", s)
			}
			cur = append(cur, pt{lat, lon})
		}
	}
	return nil, fmt.Errorf("no final END")
}

// simplifyRing returns the ring simplified to tol metres, open (the first
// point is not repeated at the end).
func simplifyRing(r []pt, tol float64) []pt {
	if len(r) > 1 && r[0] == r[len(r)-1] {
		r = r[:len(r)-1]
	}
	if len(r) < 4 {
		return r
	}
	// two halves, so Douglas-Peucker has distinct end points
	h := len(r) / 2
	closed := append(append([]pt{}, r...), r[0])
	a := douglasPeucker(closed[:h+1], tol)
	b := douglasPeucker(closed[h:], tol)
	return append(a[:len(a)-1], b[:len(b)-1]...)
}

func douglasPeucker(p []pt, tol float64) []pt {
	lat0 := 0.0
	for _, q := range p {
		lat0 += q[0]
	}
	lat0 /= float64(len(p))
	kx, ky := 111320*math.Cos(lat0*math.Pi/180), 110540.0
	xy := make([][2]float64, len(p))
	for i, q := range p {
		xy[i] = [2]float64{q[1] * kx, q[0] * ky}
	}
	keep := make([]bool, len(p))
	keep[0], keep[len(p)-1] = true, true
	stack := [][2]int{{0, len(p) - 1}}
	for len(stack) > 0 {
		ab := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		a, b := ab[0], ab[1]
		dx, dy := xy[b][0]-xy[a][0], xy[b][1]-xy[a][1]
		l := math.Hypot(dx, dy)
		best, bi := -1.0, -1
		for i := a + 1; i < b; i++ {
			px, py := xy[i][0]-xy[a][0], xy[i][1]-xy[a][1]
			d := math.Hypot(px, py)
			if l > 0 {
				d = math.Abs(dy*px-dx*py) / l
			}
			if d > best {
				best, bi = d, i
			}
		}
		if best > tol {
			keep[bi] = true
			stack = append(stack, [2]int{a, bi}, [2]int{bi, b})
		}
	}
	var out []pt
	for i, k := range keep {
		if k {
			out = append(out, p[i])
		}
	}
	return out
}
