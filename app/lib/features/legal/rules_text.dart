The map shows no-smoking zones from OpenStreetMap data (© OpenStreetMap contributors). **This data can be incomplete or wrong; the map is no legal advice.** You have to check yourself whether you may smoke at a place – also when a spot is on the map or no zone is shown.

In **Germany** consumption in public is banned by § 5 of the Consumer Cannabis Act (KCanG):

- in the immediate presence of persons under 18,
- in schools, children's and youth facilities, on playgrounds and in publicly accessible sports facilities, and within sight of them; at more than 100 metres from their entrance it no longer counts as within sight,
- in pedestrian zones between 7 am and 8 pm,
- in and within sight of cannabis clubs, and in military areas of the German armed forces.

Federal states and municipalities can add further bans (e.g. in parks, beer gardens or at fairs). Do not drive under the influence of cannabis.

**Austria, Switzerland and Liechtenstein** have their own rules: cannabis containing THC is not legal there as it is in Germany; possession and consumption can be punished. The zones shown follow the German rules. The law of the place where you are always applies.

