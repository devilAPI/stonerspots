## Nur ab 18

Stonerspots ist nur für Erwachsene. Wer jünger als 18 ist, darf sich nicht registrieren.

## Halte dich an das Gesetz

Die Karte zeigt Verbotszonen nach Daten von OpenStreetMap (© OpenStreetMap-Mitwirkende). **Diese Daten können unvollständig oder falsch sein; die Karte ist keine Rechtsberatung.** Ob du an einem Ort kiffen darfst, musst du selbst prüfen – auch dann, wenn ein Spot auf der Karte steht oder keine Zone angezeigt wird.

In **Deutschland** ist der Konsum in der Öffentlichkeit nach § 5 Konsumcannabisgesetz (KCanG) verboten:

- in unmittelbarer Gegenwart von Personen unter 18 Jahren,
- in Schulen, Kinder- und Jugendeinrichtungen, auf Kinderspielplätzen und in öffentlich zugänglichen Sportstätten sowie in deren Sichtweite; Sichtweite ist bei mehr als 100 Metern Abstand vom Eingangsbereich nicht mehr gegeben,
- in Fußgängerzonen zwischen 7 und 20 Uhr,
- in und in Sichtweite von Anbauvereinigungen und in militärischen Bereichen der Bundeswehr.

Bundesländer und Gemeinden können weitere Verbote erlassen (z. B. in Parks, Biergärten oder auf Volksfesten). Fahr nicht unter Einfluss von Cannabis.

In **Österreich, der Schweiz und Liechtenstein** gelten eigene Regeln: Cannabis mit THC ist dort nicht wie in Deutschland legalisiert; Besitz und Konsum können bestraft werden. Die angezeigten Zonen folgen den deutschen Regeln. Es gilt immer das Recht des Ortes, an dem du bist.

## Was nicht auf Stonerspots gehört

- Spots an oder in Sichtweite von Schulen, Spielplätzen, Kinder- und Jugendeinrichtungen und Sportstätten und Spots in Fußgängerzonen.
- Spots auf Privatgrundstücken ohne Erlaubnis.
- Rechtswidrige Inhalte, z. B. Angebote zum Kauf, Verkauf oder zur Weitergabe von Cannabis, Beleidigungen, Hetze, Drohungen oder Gewalt.
- Fotos und Texte, an denen du keine Rechte hast.
- Personenbezogene Daten anderer: keine erkennbaren Personen auf Fotos ohne ihre Einwilligung, keine Kfz-Kennzeichen, Namen oder Adressen, keine Wohnadressen als Spots.
- Werbung und Spam.

